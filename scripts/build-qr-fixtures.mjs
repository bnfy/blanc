// One-time reference fixtures for src/renderer/pages/qr-code.js (design
// 2026-10-28 §6.2). Blanc's encoder is first-party; these matrices come from
// an independent reference encoder so the tests compare against something
// Blanc didn't write. Not run in CI and not a dependency: install the
// reference in a scratch folder and pass its path.
//
//   npm install --prefix /tmp/qrref --ignore-scripts qrcode@1.5.4
//   node scripts/build-qr-fixtures.mjs /tmp/qrref/node_modules/qrcode
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const reference = process.argv[2];
if (!reference) throw new Error('usage: node scripts/build-qr-fixtures.mjs <path to the qrcode package>');
const QRCode = createRequire(import.meta.url)(path.resolve(reference));
const version = JSON.parse(fs.readFileSync(path.join(reference, 'package.json'), 'utf8')).version;

const rows = (symbol) => {
  const { size, data } = symbol.modules;
  return Array.from({ length: size }, (_, r) => Array.from({ length: size }, (_, c) => (data[r * size + c] ? '1' : '0')).join(''));
};
const make = (text, maskPattern) => {
  const symbol = QRCode.create([{ data: text, mode: 'byte' }], { errorCorrectionLevel: 'M', ...(maskPattern === undefined ? {} : { maskPattern }) });
  return { text, version: symbol.version, mask: symbol.maskPattern, forcedMask: maskPattern ?? null, rows: rows(symbol) };
};

const cases = [];
for (const code of ['K7MR4PX2', 'ABCDEFGH', '23456789', 'ZZZZ2222', 'HJKM9876']) cases.push(make(`https://blanc.day/pair#${code}`));
cases.push(make('A'));
cases.push(make('Blanc'));
cases.push(make('x'.repeat(62)));
for (let mask = 0; mask < 8; mask += 1) cases.push(make('https://blanc.day/pair#K7MR4PX2', mask));

const out = path.resolve('test/unit/fixtures/qr/pair-links.json');
fs.writeFileSync(out, JSON.stringify({ note: `Byte mode, level M. Generated by scripts/build-qr-fixtures.mjs from the reference encoder qrcode@${version}; '1' is a dark module.`, cases }, null, 1) + '\n');
console.log(`wrote ${out}: ${cases.length} cases`);
