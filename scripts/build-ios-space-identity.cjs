'use strict';
// Writes (or, with --check, verifies) the iPhone's copy of the Space presets
// and symbols from src/renderer/space-identity.js, the single source.
const fs = require('node:fs');
const path = require('node:path');
const identity = require('../src/renderer/space-identity.js');
const dest = path.resolve(__dirname, '../ios/Blanc/Blanc/SpaceIdentity.generated.swift');
const str = (value) => JSON.stringify(String(value));
const element = ([tag, attrs]) => {
  const pairs = Object.entries(attrs).map(([k, v]) => `${str(k)}: ${str(v)}`).join(', ');
  return `.init(tag: ${str(tag)}, attributes: [${pairs}])`;
};
const lines = [
  '// Generated by scripts/build-ios-space-identity.cjs from',
  '// src/renderer/space-identity.js. Do not edit; run',
  '// `npm run ios:space-identity:build`.',
  '// Symbol geometry is Lucide\'s (ISC; see THIRD-PARTY-NOTICES.md).',
  '',
  'extension SpaceIdentity {',
  '    static let presets: [(id: String, hex: String)] = [',
  ...identity.PRESETS.map((p) => `        (${str(p.id)}, ${str(p.hex)}),`),
  '    ]',
  '',
  '    static let symbolIds: [String] = [',
  ...identity.SYMBOL_IDS.map((id) => `        ${str(id)},`),
  '    ]',
  '',
  '    static let symbols: [String: [SVGElement]] = [',
  ...identity.SYMBOL_IDS.map((id) => `        ${str(id)}: [${identity.SYMBOLS[id].map(element).join(', ')}],`),
  '    ]',
  '',
  `    static let spacesGlyph: [SVGElement] = [${identity.SPACES_GLYPH.map(element).join(', ')}]`,
  '',
  '    static let surfaces: [String: [String]] = [',
  ...Object.entries(identity.SURFACES).map(([theme, list]) => `        ${str(theme)}: [${list.map(str).join(', ')}],`),
  '    ]',
  '}',
  '',
];
const output = lines.join('\n');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(dest) || fs.readFileSync(dest, 'utf8') !== output) {
    console.error('SpaceIdentity.generated.swift is stale; run npm run ios:space-identity:build');
    process.exit(1);
  }
} else {
  fs.writeFileSync(dest, output);
}
