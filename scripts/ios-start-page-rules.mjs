// Bundle the desktop's pure appearance rules for the iOS document-start shim.
import fs from 'node:fs';
const modules = {
  identity: 'src/renderer/space-identity.js',
  paint: 'src/main/start-page-paint.js',
  ink: 'src/renderer/pages/clock-ink.js',
  clock: 'src/main/start-clock-style.js',
};
let source = '// Generated by scripts/ios-start-page-rules.mjs; do not edit.\n(() => {\nconst modules = {};\n';
for (const [id, path] of Object.entries(modules)) {
  source += `modules.${id} = (() => { const module = { exports: {} }; const require = name => ({ '../renderer/space-identity': modules.identity, './start-page-paint': modules.paint, '../renderer/pages/clock-ink': modules.ink })[name];\n${fs.readFileSync(new URL('../' + path, import.meta.url), 'utf8')}\nreturn module.exports; })();\n`;
}
source += 'globalThis.BlancStartRules = { paint: modules.paint, clock: modules.clock, presets: modules.identity.PRESETS };\n})();\n';
const output = new URL('../src/renderer/pages/ios-start-rules.js', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== source) throw new Error('iOS appearance rules are stale');
} else fs.writeFileSync(output, source);
