// Keep the iOS Start Page's supported layouts and first-run default aligned
// with the shared schema without importing unrelated desktop-only settings.
import fs from 'node:fs';
const schema = JSON.parse(fs.readFileSync(new URL('../settings-schema/schema.json', import.meta.url), 'utf8'));
const output = new URL('../ios/Blanc/Blanc/StartPageDefaults.swift', import.meta.url);
const source = `// Generated by scripts/ios-start-page-settings.mjs; do not edit.\nimport Foundation\n\n` +
  `enum BlancStartPageLayout: String, CaseIterable { case ${schema.newtabLayouts.join(', ')} }\n\n` +
  `enum MobileStartPageDefaults {\n    static let layout: BlancStartPageLayout = .${schema.defaults.newtabLayout}\n}\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== source) throw new Error('iOS Start Page defaults are stale');
} else {
  fs.writeFileSync(output, source);
}
