"""Embed the served Island assets as static byte arrays (no disk at runtime)."""
import argparse
import os

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--served', required=True)
parser.add_argument('--root', required=True)
parser.add_argument('--output', required=True)
args = parser.parse_args()

def literal(data):
    # Printable ASCII stays readable; everything else is a 3-digit octal
    # escape, so a following digit can never extend it. '?' avoids trigraphs.
    out, line = [], []
    for byte in data:
        ch = chr(byte)
        line.append(ch if 0x20 <= byte < 0x7f and ch not in '\\"?' else '\\%03o' % byte)
        if len(line) >= 16384:
            out.append('"' + ''.join(line) + '"'); line = []
    out.append('"' + ''.join(line) + '"')
    return '\n'.join(out)

paths = [p for p in open(args.served).read().split('\n') if p]
if len(set(paths)) != len(paths) or any(p.startswith('/') or '..' in p.split('/') for p in paths):
    raise SystemExit('Invalid served list')
parts = ['// Generated by //blanc/island_resources/embed.py. Do not edit.',
         '#include "blanc/island_resources/island_resources.h"', '',
         '#include <algorithm>', '#include <iterator>', '',
         'namespace blanc::island_resources {', 'namespace {']
for index, path in enumerate(paths):
    data = open(os.path.join(args.root, path), 'rb').read()
    parts.append(f'// {path}\nconstexpr char kData{index}[] =\n{literal(data)};\nconstexpr size_t kSize{index} = {len(data)};')
parts.append('struct Asset { std::string_view path; const char* data; size_t size; };')
parts.append('constexpr Asset kAssets[] = {')
parts += [f'    {{"{p}", kData{i}, kSize{i}}},' for i, p in enumerate(paths)]
parts += ['};', '}  // namespace', '',
          'const Asset* Lookup(std::string_view path) {',
          '  const auto* it = std::ranges::find(kAssets, path, &Asset::path);',
          '  return it == std::end(kAssets) ? nullptr : it;', '}', '',
          'bool IsServed(std::string_view path) { return Lookup(path) != nullptr; }', '',
          'scoped_refptr<base::RefCountedMemory> Find(std::string_view path) {',
          '  const Asset* asset = Lookup(path);',
          '  if (!asset) return nullptr;',
          '  return base::MakeRefCounted<base::RefCountedStaticMemory>(',
          '      base::as_byte_span(std::string_view(asset->data, asset->size)));', '}', '',
          '}  // namespace blanc::island_resources', '']
with open(args.output, 'w') as f:
    f.write('\n'.join(parts))
