// Writes Android's Space symbols from src/renderer/space-identity.js, the source desktop and the
// iPhone draw from (geometry Lucide's, ISC). --check fails when a file is stale.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';

const chromium = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(chromium, 'blanc/android/island/res/drawable');
const {SYMBOL_IDS, SYMBOLS, SPACES_GLYPH} = createRequire(import.meta.url)(path.join(chromium, '../src/renderer/space-identity.js'));

// One SVG element as path data.
export function pathData([tag, a]) {
  const n = name => Number(a[name] ?? 0);
  if (tag === 'path') return a.d;
  if (tag === 'circle') {
    const {cx, cy, r} = a;
    return `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0`;
  }
  if (tag === 'rect') {
    const x = n('x'), y = n('y'), w = n('width'), h = n('height'), r = n('rx');
    return `M${x + r},${y}h${w - 2 * r}a${r},${r} 0 0 1 ${r},${r}v${h - 2 * r}a${r},${r} 0 0 1 ${-r},${r}h${-(w - 2 * r)}a${r},${r} 0 0 1 ${-r},${-r}v${-(h - 2 * r)}a${r},${r} 0 0 1 ${r},${-r}z`;
  }
  if (tag === 'line') return `M${a.x1},${a.y1}L${a.x2},${a.y2}`;
  throw Error(`unknown element ${tag}`);
}

export const vector = elements => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by chromium/tools/android-space-icons.mjs. Don't edit. Geometry: Lucide (ISC). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${elements.map(element => `    <path
        android:pathData="${pathData(element)}"
        android:strokeColor="#FFFFFFFF"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:strokeWidth="2" />`).join('\n')}
</vector>
`;

// The card's row controls, from Lucide as the symbols are.
const path_ = d => ['path', {d}];
const CONTROLS = {
  check: [path_('M20 6 9 17l-5-5')],
  arrow_up: [path_('m5 12 7-7 7 7'), path_('M12 19V5')],
  arrow_down: [path_('M12 5v14'), path_('m19 12-7 7-7-7')],
  pencil: [path_('M21.174 6.812a1 1 0 0 0-3.986-3.987L3.842 16.174a2 2 0 0 0-.5.83l-1.321 4.352a.5.5 0 0 0 .623.622l4.353-1.32a2 2 0 0 0 .83-.497z'),
    path_('m15 5 4 4')],
};

export function files() {
  const out = {blanc_spaces_glyph: vector(SPACES_GLYPH)};
  for (const [name, elements] of Object.entries(CONTROLS)) out[`blanc_spaces_${name}`] = vector(elements);
  for (const id of SYMBOL_IDS) out[`blanc_space_${id}`] = vector(SYMBOLS[id]);
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  for (const [name, text] of Object.entries(files())) {
    const file = path.join(OUT, `${name}.xml`);
    if (!check) fs.writeFileSync(file, text);
    else if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== text) { console.error(`${name} is stale`); process.exit(1); }
  }
  console.log(`${Object.keys(files()).length} icons`);
}
