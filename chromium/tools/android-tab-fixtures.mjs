// Writes the differential fixtures for Blanc for Android's tab rules (A2 plan,
// Task 2): what desktop's own code at v1.46.0 answers — src/renderer/tab-sections.js
// for sections and order, src/main/group-name-case.js for group names — over
// generated inputs, as Java sources the Robolectric tests read.
// --check fails when the committed files are stale.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {javaString} from './android-address-fixtures.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SHIPPING = '6479ed3a314e4fd6219b8de1598bacffa78b4d7c'; // v1.46.0
const DIR = path.join(root, 'blanc/android/junit/src/org/chromium/blanc/tabs');

function shipped(file) {
  const module = {exports: {}};
  const source = execFileSync('git', ['show', `${SHIPPING}:${file}`], {cwd: root, encoding: 'utf8'});
  vm.runInNewContext(source, {module, exports: module.exports});
  return module.exports;
}

// A small deterministic generator (mulberry32), so the fixtures never change by themselves.
function random(seed) {
  return () => {
    seed |= 0; seed = seed + 0x6d2b79f5 | 0;
    let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}

// Tab lists of up to 10 tabs across three groups, some pinned, in any order.
export function tabLists(count) {
  const next = random(1);
  const lists = [[]];
  while (lists.length < count) {
    const n = 1 + Math.floor(next() * 10);
    lists.push(Array.from({length: n}, (_, i) => {
      const g = Math.floor(next() * 5);
      return {id: `t${i}`, groupId: g < 3 ? `g${g}` : null, pinned: next() < 0.2};
    }));
  }
  return lists;
}

export const encodeList = list => list.map(t => `${t.id}:${t.groupId ?? ''}:${t.pinned ? 'p' : ''}`).join(',');

export function groupNameInputs() {
  const next = random(2);
  const pieces = ['Research', 'research', 'RESEARCH', ' ', ' ', '　', '\t', 'İ', 'ı', 'Σ', 'ς', 'ß', 'é', '😀', 'a', 'Z', '-', 'Ǆ'];
  const names = ['', ' ', 'Research', 'research', '  padded ', 'x'.repeat(40), 'x'.repeat(41), 'İstanbul', 'ΣΟΦΟΣ', 'ΟΔΟΣ ΣΟΦΟΣ', '😀'.repeat(20), '😀'.repeat(21), '﻿BOM', 'Straße'];
  while (names.length < 400) {
    const n = 1 + Math.floor(next() * 45);
    names.push(Array.from({length: n}, () => pieces[Math.floor(next() * pieces.length)]).join(''));
  }
  return [...new Set(names)];
}

function render() {
  const sections = shipped('src/renderer/tab-sections.js');
  const names = shipped('src/main/group-name-case.js');
  const sectionRows = tabLists(300).map(list => {
    const out = sections.sectionsOf(list).map(s => `${s.groupId ?? ''}|${s.tabIds.join(',')}`).join(';');
    return `        {${javaString(encodeList(list))}, ${javaString(out)}, ${javaString(sections.normalizeOrder(list).join(','))}},`;
  });
  const nameRows = groupNameInputs().map(name =>
    `        {${javaString(name)}, ${javaString(names.normalizeGroupName(name))}, ${javaString(names.groupNameKey(name))}},`);
  const file = (cls, what, rows) => `// Copyright 2026 Bananify Creative. MIT; see LICENSE.
// GENERATED by chromium/tools/android-tab-fixtures.mjs from desktop v1.46.0; do not edit.

package org.chromium.blanc.tabs;

/** ${what} */
final class ${cls} {
    static final String[][] ROWS = {
${rows.join('\n')}
    };

    private ${cls}() {}
}
`;
  return {
    'TabSectionsFixtures.java': file('TabSectionsFixtures', 'Desktop\'s sectionsOf and normalizeOrder: {tabs as id:group:p, sections as group|ids;…, order}.', sectionRows),
    'GroupNamesFixtures.java': file('GroupNamesFixtures', 'Desktop\'s normalizeGroupName and groupNameKey: {input, normalized, key}.', nameRows),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const stale = [];
  for (const [name, text] of Object.entries(render())) {
    const target = path.join(DIR, name);
    let current = null;
    try { current = fs.readFileSync(target, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (current === text) continue;
    if (check) stale.push(name);
    else { fs.mkdirSync(DIR, {recursive: true}); fs.writeFileSync(target, text); }
  }
  if (stale.length) { console.error(`Stale tab fixtures: ${stale.join(', ')}; run node chromium/tools/android-tab-fixtures.mjs`); process.exitCode = 1; }
}
