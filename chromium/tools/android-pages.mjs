// Blanc for Android's pages (A1 plan, Task 6): byte-identical copies of
// shipping's page files at the commit pinned in blanc/android/pages.json,
// in blanc/android/pages/. The Android WebUI (chrome://blanc/) serves them
// with blanc/android/pages-adapter/, as the iPhone serves the same files.
// The Start Page is the desktop fork's (A5b): pages.json's `start` files are
// copied, byte for byte, from that folder of this tree into pages/start/, and
// its `alongside` files into pages/ beside them.
// It also writes the adapter from its template and browser-api/bridges.json.
//   node chromium/tools/android-pages.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const chromium = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LIST = path.join(chromium, 'blanc/android/pages.json');
export const PAGES_DIR = path.join(chromium, 'blanc/android/pages');
// The pages Android 1.0 opens, as the iPhone's BlancPageResolver lists them (without Downloads).
export const PAGES = ['newtab', 'bookmarks', 'history', 'shortcuts', 'error', 'mahjong'];

// The file's bytes, or null if it isn't there: one read, so nothing can change between a check and it.
function readIfPresent(file) {
  try { return fs.readFileSync(file); } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

export const pinned = () => JSON.parse(fs.readFileSync(LIST, 'utf8'));

const ADAPTER_DIR = path.join(chromium, 'blanc/android/pages-adapter');
export const ADAPTER = path.join(ADAPTER_DIR, 'android-pages-adapter.js');

// bridges.json's bowserPages members for the pages Android serves, each with
// only those of its hosts (the iPhone's makeUserScript list, filtered).
export function adapterMembers() {
  const bridges = JSON.parse(fs.readFileSync(path.join(chromium, '../browser-api/bridges.json'), 'utf8'));
  return bridges.bowserPages.members
    .map(({name, kind, hosts}) => ({name, kind, hosts: hosts.filter(h => PAGES.includes(h))}))
    .filter(m => m.hosts.length);
}

const adapterSource = () => fs.readFileSync(path.join(ADAPTER_DIR, 'android-pages-adapter.template.js'), 'utf8')
  .replace('const MEMBERS = __BLANC_MEMBERS__', 'const MEMBERS = ' + JSON.stringify(adapterMembers()))
  .replace('const PAGES = __BLANC_PAGES__', 'const PAGES = ' + JSON.stringify(PAGES))
  .replace(/^\/\/ Blanc for Android's page adapter/, "// GENERATED by tools/android-pages.mjs from android-pages-adapter.template.js.\n// Blanc for Android's page adapter");

export const START_DIR = path.join(PAGES_DIR, 'start');

const shipped = (commit, file) =>
  execFileSync('git', ['show', `${commit}:src/renderer/pages/${file}`], {cwd: chromium, maxBuffer: 64 * 1024 * 1024});

// Every file the tool writes, as [target, bytes, where it came from].
export function wanted() {
  const {commit, files, start} = pinned();
  const out = [];
  for (const file of files) out.push([path.join(PAGES_DIR, file), () => shipped(commit, file), commit.slice(0, 9)]);
  for (const file of start.files)
    out.push([path.join(START_DIR, file), () => fs.readFileSync(path.join(chromium, start.from, file)), start.from]);
  for (const [file, from] of Object.entries(start.alongside || {}))
    out.push([path.join(PAGES_DIR, file), () => fs.readFileSync(path.join(chromium, from)), from]);
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const problems = [];
  fs.mkdirSync(START_DIR, {recursive: true});
  const targets = new Set();
  for (const [target, bytes, from] of wanted()) {
    targets.add(target);
    const want = bytes();
    const have = readIfPresent(target);
    if (have && have.equals(want)) continue;
    if (check) problems.push(`${path.relative(PAGES_DIR, target)} differs from ${from}`);
    else fs.writeFileSync(target, want);
  }
  for (const dir of [PAGES_DIR, START_DIR]) {
    for (const extra of fs.readdirSync(dir)) {
      const target = path.join(dir, extra);
      if (targets.has(target) || target === START_DIR) continue;
      if (check) problems.push(`${path.relative(PAGES_DIR, target)} is not listed`);
      else fs.rmSync(target);
    }
  }
  const adapter = adapterSource();
  if (readIfPresent(ADAPTER)?.toString('utf8') !== adapter) {
    if (check) problems.push('pages-adapter/android-pages-adapter.js is not its template plus bridges.json');
    else fs.writeFileSync(ADAPTER, adapter);
  }
  if (problems.length) {
    console.error(`Android pages are stale:\n  ${problems.join('\n  ')}\nRun node chromium/tools/android-pages.mjs.`);
    process.exitCode = 1;
  }
}
