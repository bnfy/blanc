#!/usr/bin/env node
// The native menu labels Blanc uses: Chromium's private-browsing items on
// macOS (D1: a private tab, not an incognito window) and the Island address
// input's menu (F19), generated from shipping's published catalogs for each
// selectable language.
//   node chromium/tools/menu-strings.mjs --write | --check
// The release is the one blanc/island-renderer.json records.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const header = path.join(root, 'blanc/common/menu_strings.h');
const {ref, commit} = JSON.parse(fs.readFileSync(path.join(root, 'blanc/island-renderer.json'), 'utf8'));
// Struct field, shipping message key.
export const LABELS = [['new_private_tab', 'menu.newPrivateTab'], ['new_private_window', 'menu.newPrivateWindow'],
  // The Island address input's menu (F19), shipping's address-menu-model.js.
  ['undo', 'menu.undo'], ['redo', 'menu.redo'], ['cut', 'menu.cut'], ['copy', 'menu.copy'],
  ['copy_clean_link', 'menu.copyCleanLink'], ['paste', 'menu.paste'],
  ['paste_and_go', 'addressMenu.pasteAndGo'], ['delete_text', 'menu.delete'], ['select_all', 'menu.selectAll']];

const show = file => execFileSync('git', ['show', `${ref}:${file}`], {cwd: root, encoding: 'utf8'});

export function catalogs(labels = LABELS) {
  const locales = JSON.parse(show('src/main/i18n-locales.json')).filter(l => l.status === 'selectable');
  return locales.map(({code}) => {
    const context = {module: {exports: {}}};
    vm.runInNewContext(show(`src/renderer/pages/strings.${code}.js`), context);
    const values = labels.map(([, key]) => {
      const value = context.module.exports.messages?.[key];
      if (typeof value !== 'string' || !value) throw Error(`${code}: missing ${key}`);
      return value;
    });
    return {code, values};
  });
}

export function generate(rows = catalogs()) {
  const id = code => code.replace('-', '_');
  const fallback = rows.filter(({code}) => code !== 'en').map(({code}) =>
    `  if (primary == "${code.split('-')[0]}") return kLabels_${id(code)};`).join('\n');
  return `// Generated by chromium/tools/menu-strings.mjs from shipping ${ref}
// (${commit}); do not edit.
#ifndef BLANC_COMMON_MENU_STRINGS_H_
#define BLANC_COMMON_MENU_STRINGS_H_

#include <string>
#include <string_view>

namespace blanc::menu {

struct Labels {
${LABELS.map(([field]) => `  std::u16string_view ${field};`).join('\n')}
};
${rows.map(({code, values}) => `inline constexpr Labels kLabels_${id(code)} = {${values.map(v => `u${JSON.stringify(v)}`).join(', ')}};`).join('\n')}

// Chromium's application locale chooses, as for the menus around these
// items; a region falls back to its language (de-AT -> de, pt-PT -> pt-BR)
// and anything else to English, as shipping's resolveLocale does.
inline const Labels& ForLocale(std::string locale) {
  for (char& c : locale) c = c == '_' ? '-' : (c >= 'A' && c <= 'Z') ? static_cast<char>(c + 32) : c;
  const std::string primary = locale.substr(0, locale.find('-'));
${fallback}
  return kLabels_en;
}

}  // namespace blanc::menu

#endif  // BLANC_COMMON_MENU_STRINGS_H_
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate();
  if (process.argv.includes('--write')) {
    fs.writeFileSync(header, text);
    console.log(`Wrote ${path.relative(root, header)} from ${ref}`);
  } else if (process.argv.includes('--check')) {
    if (!fs.existsSync(header) || fs.readFileSync(header, 'utf8') !== text)
      throw Error(`${path.relative(root, header)} differs from ${ref}; run --write`);
    console.log(`Menu labels match ${ref}`);
  } else {
    throw Error('Usage: menu-strings.mjs --write | --check');
  }
}
