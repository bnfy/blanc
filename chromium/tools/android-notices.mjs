// Android A7: byte copies of Blanc's notices and this page's current translations.
//   node chromium/tools/android-notices.mjs [--check]
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const SOURCES = [
  ['LICENSE.txt', 'LICENSE'],
  ['ASSET-LICENSE.txt', 'ASSET-LICENSE.md'],
  ['THIRD-PARTY-NOTICES.txt', 'THIRD-PARTY-NOTICES.md'],
  ['CHROMIUM-FORK-NOTICES.txt', 'chromium/THIRD_PARTY_NOTICES.md'],
];

export function notices() {
  return SOURCES.map(([file, source]) => ({
    file: `notices/${file}`, source,
    sha256: createHash('sha256').update(fs.readFileSync(path.join(ROOT, source))).digest('hex'),
  }));
}

// The existing pages keep their shipped strings pin. This page alone needs the
// current android.licenses.* keys, selected by the WebUI's ui-language.js.
function strings() {
  const catalogs = {};
  for (const locale of ['en', 'de', 'es', 'fr', 'it', 'pt-BR']) {
    const catalog = JSON.parse(fs.readFileSync(path.join(ROOT, `copy/messages/${locale}.json`), 'utf8'));
    catalogs[locale] = Object.fromEntries(Object.entries(catalog)
      .filter(([key]) => key.startsWith('android.licenses.')).map(([key, entry]) => [key, entry.message]));
  }
  return '// GENERATED by tools/android-notices.mjs from copy/messages. Do not edit.\n'
    + '(function () {\n'
    + `  const catalogs = ${JSON.stringify(catalogs)};\n`
    + "  const locale = Object.hasOwn(catalogs, window.__blancUiLanguage) ? window.__blancUiLanguage : 'en';\n"
    + "  window.blancStrings = {locale, dir: 'ltr', messages: catalogs[locale], fallback: catalogs.en};\n"
    + '})();\n';
}

function readIfPresent(file) {
  try { return fs.readFileSync(file); } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check');
  const pages = path.join(ROOT, 'chromium/blanc/android/pages');
  const files = notices().map(({file, source}) => [file, fs.readFileSync(path.join(ROOT, source))]);
  files.push(['licenses-strings.js', Buffer.from(strings())]);
  const stale = [];
  for (const [file, bytes] of files) {
    const target = path.join(pages, file);
    if (readIfPresent(target)?.equals(bytes)) continue;
    if (check) stale.push(file);
    else {
      fs.mkdirSync(path.dirname(target), {recursive: true});
      fs.writeFileSync(target, bytes);
    }
  }
  if (stale.length) {
    console.error(`Android notices are stale:\n  ${stale.join('\n  ')}\nRun node chromium/tools/android-notices.mjs.`);
    process.exitCode = 1;
  }
}
