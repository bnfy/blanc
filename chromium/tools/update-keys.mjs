#!/usr/bin/env node
// Blanc's Windows update keys in the build (W3 Task B3): writes
// blanc/branding/win-beta/cup_public_key.h from windows/keys/cup-public.der and
// updater.gni's crx_pkhash from windows/keys/crx-public.der.
//
//   node chromium/tools/update-keys.mjs --check | --write
import crypto from 'node:crypto';
import fs from 'node:fs';
import {fileURLToPath} from 'node:url';

const file = rel => fileURLToPath(new URL(`../${rel}`, import.meta.url));
export const CUP_KEY_VERSION = 1;

// The header Blanc's updater includes: its CUP key version and ML-DSA-44
// SubjectPublicKeyInfo, as request_sender.cc holds Google's.
export function cupHeader(der, version) {
  const rows = [];
  for (let i = 0; i < der.length; i += 12)
    rows.push('    ' + [...der.subarray(i, i + 12)].map(b => `0x${b.toString(16).padStart(2, '0')}`).join(', ') + ',');
  return `// Generated by chromium/tools/update-keys.mjs from chromium/windows/keys/cup-public.der.
// Do not edit. Blanc's update-check (CUP) key for the Windows beta's updater:
// an ML-DSA-44 SubjectPublicKeyInfo; the private half is the update Worker's.

#ifndef BLANC_BRANDING_WIN_BETA_CUP_PUBLIC_KEY_H_
#define BLANC_BRANDING_WIN_BETA_CUP_PUBLIC_KEY_H_

#include <array>
#include <cstdint>

namespace blanc_updater {

inline constexpr int kCupKeyVersion = ${version};
inline constexpr auto kCupPublicKey = std::to_array<uint8_t>({
${rows.join('\n')}
});

}  // namespace blanc_updater

#endif  // BLANC_BRANDING_WIN_BETA_CUP_PUBLIC_KEY_H_
`;
}

// updater.gni's crx_pkhash: base64 SHA-256 of the publisher SubjectPublicKeyInfo.
export const crxPkHash = der => crypto.createHash('sha256').update(der).digest('base64');

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const mode = process.argv[2];
  if (mode !== '--check' && mode !== '--write') { console.error('usage: update-keys.mjs --check | --write'); process.exit(2); }
  const header = cupHeader(fs.readFileSync(file('windows/keys/cup-public.der')), CUP_KEY_VERSION);
  const gniPath = file('blanc/branding/win-beta/updater.gni'), gni = fs.readFileSync(gniPath, 'utf8');
  const nextGni = gni.replace(/^crx_pkhash = "[^"]*"$/m, `crx_pkhash = "${crxPkHash(fs.readFileSync(file('windows/keys/crx-public.der')))}"`);
  const headerPath = file('blanc/branding/win-beta/cup_public_key.h');
  // One read: a missing header reads as empty (no check-then-read race).
  let current = '';
  try { current = fs.readFileSync(headerPath, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (mode === '--write') { fs.writeFileSync(headerPath, header); fs.writeFileSync(gniPath, nextGni); console.log('written'); }
  else if (current !== header || nextGni !== gni) { console.error('update keys are stale; run --write'); process.exit(1); }
  else console.log('current');
}
