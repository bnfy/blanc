// Writes the Android address port's differential fixtures (A1 plan, Task 5):
// what the Island's verified JavaScript port (blanc/island/address-input.js,
// itself checked against shipping v1.45.1) answers for every input of the
// shared corpus, as a Java source file the Robolectric test reads.
// --check fails when the committed file is stale.
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {corpus} from './address-corpus.mjs';

// The file's text, or null if it isn't there: one read, so nothing can change between a check and it.
function readIfPresent(file) {
  try { return fs.readFileSync(file, 'utf8'); } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SHIPPING = '85883b1afa11375e1300130914d6f40c5388af21';
export const OUT = path.join(root, 'blanc/android/junit/src/org/chromium/blanc/address/AddressFixtures.java');

function shippingProtocols() {
  const source = execFileSync('git', ['show', `${SHIPPING}:src/main/external-protocols.js`], {cwd: root, encoding: 'utf8'});
  const module = {exports: {}};
  vm.runInNewContext(source, {module, exports: module.exports, URL,
    require: name => { if (name === './blocking-resources') return {PDF_VIEWER_ORIGIN: ''}; throw Error('unexpected require ' + name); }});
  return [...module.exports.DENIED_HANDOFF_PROTOCOLS, ...module.exports.DIRECT_HANDOFF_PROTOCOLS];
}

// A Java string literal for any text: ASCII printable as is, everything else escaped.
export function javaString(text) {
  let out = '"';
  for (const ch of text) {
    const code = ch.codePointAt(0);
    if (ch === '"' || ch === '\\') out += '\\' + ch;
    else if (code >= 0x20 && code < 0x7f) out += ch;
    else for (const unit of String.fromCodePoint(code).split('')) out += '\\u' + unit.charCodeAt(0).toString(16).padStart(4, '0');
  }
  return out + '"';
}

export function render() {
  const port = createRequire(import.meta.url)(path.join(root, 'blanc/island/address-input.js'));
  const seen = new Set();
  const rows = [];
  for (const input of corpus(shippingProtocols())) {
    if (seen.has(input)) continue;
    seen.add(input);
    const r = port.interpret(input);
    const value = r.kind === 'search' ? r.query : r.url;
    rows.push(`        {${javaString(input)}, ${javaString(r.kind)}, ${javaString(value)}, ${javaString(String(r.confirm === true))}},`);
  }
  return `// Copyright 2026 Bananify Creative. MIT; see LICENSE.
// Generated by chromium/tools/android-address-fixtures.mjs; do not edit.

package org.chromium.blanc.address;

/** What blanc/island/address-input.js answers: {input, kind, url or query, confirm}. */
final class AddressFixtures {
    static final String[][] ROWS = {
${rows.join('\n')}
    };

    private AddressFixtures() {}
}
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = render();
  const current = readIfPresent(OUT);
  if (process.argv.includes('--check')) {
    if (current !== next) { console.error('Stale address fixtures; run node chromium/tools/android-address-fixtures.mjs'); process.exitCode = 1; }
  } else if (current !== next) {
    fs.mkdirSync(path.dirname(OUT), {recursive: true});
    fs.writeFileSync(OUT, next);
  }
}
