#!/usr/bin/env node
// Blanc Beta's own third-party notice, packaged as
// Contents/Resources/notices/THIRD_PARTY_NOTICES.txt. It covers what Blanc
// adds to Chromium: the Island's fonts, data and icons (sbom-extra.json and
// compliance/policy.json) and the embedded blocker
// (chromium/blanc/third_party/blocker/bundle.json), each with its full licence
// text. Chromium's own components are in Chromium-credits.html beside it, and
// Sparkle's licence in Sparkle-LICENSE. The Electron app's notice
// (compliance/THIRD_PARTY_NOTICES.txt) describes a different product and is
// never packaged in the beta.
//
//   node chromium/release/fork-notice.mjs          write the notice
//   node chromium/release/fork-notice.mjs --check  fail if it is out of date
import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';
import {check, equal, sha256} from './policy.mjs';

export const ROOT = path.resolve(import.meta.dirname, '../..');
export const NOTICE = 'chromium/blanc/notices/THIRD_PARTY_NOTICES.txt';
const BLOCKER = 'chromium/blanc/third_party/blocker';

export function blockerBundle(root = ROOT) {
  const bundle = JSON.parse(fs.readFileSync(path.join(root, BLOCKER, 'bundle.json')));
  const header = fs.readFileSync(path.join(root, 'chromium/blanc/services/blocker/bundle_hash.h'), 'utf8');
  equal(bundle.bundleSha256, header.match(/kBlancBlockerBundleSha256\[\] = "([0-9a-f]{64})"/)?.[1], 'blocker provenance is for the pinned bundle');
  const pinned = JSON.parse(fs.readFileSync(path.join(root, 'adblock/sources/pinned.json')));
  equal(bundle.filters.combinedSha256, pinned.combinedSha256, 'the bundle was made from the pinned filter lists');
  for (const entry of [...bundle.packages, bundle.proceduralRenderer]) for (const f of entry.licenseFiles)
    equal(sha256(fs.readFileSync(path.join(root, BLOCKER, f.file))), f.sha256, `blocker licence text changed: ${f.file}`);
  return bundle;
}

export function makeNotice(root = ROOT) {
  const policy = JSON.parse(fs.readFileSync(path.join(root, 'compliance/policy.json')));
  const extra = JSON.parse(fs.readFileSync(path.join(root, 'chromium/release/sbom-extra.json')));
  const asset = id => { const a = policy.assets.find(x => x.id === id); check(a, `unknown compliance asset: ${id}`); return a; };
  const bundle = blockerBundle(root);
  const texts = new Map();
  const cite = file => {
    const bytes = fs.readFileSync(path.join(root, file)), digest = sha256(bytes);
    if (!texts.has(digest)) texts.set(digest, {n: texts.size + 1, bytes});
    return `Licence text ${texts.get(digest).n} below`;
  };
  const item = (name, version, license, lines) => `- ${name}${version ? ` ${version}` : ''} — ${license}\n` + lines.filter(Boolean).map(l => `  ${l}\n`).join('');
  let out = 'BLANC BETA THIRD-PARTY NOTICES\n\n' +
    'Generated by chromium/release/fork-notice.mjs. Do not edit by hand.\n' +
    'Blanc itself is released under the MIT License; LICENSE is beside this notice.\n' +
    'Blanc Beta is built on Chromium: its components and their licences are listed in\n' +
    'Chromium-credits.html, with Chromium\'s own licence in Chromium-LICENSE. The Sparkle\n' +
    'update framework\'s licence is in Sparkle-LICENSE. This notice covers what Blanc adds.\n';
  out += '\nINTERFACE FONTS, DATA AND ICONS\n\n';
  for (const entry of extra.blancAssets) {
    const a = entry.asset ? asset(entry.asset) : entry;
    const attribution = entry.attribution || a.attribution;
    out += item(a.name, a.version, a.license, [attribution && `Attribution: ${attribution}`, `Source: ${a.homepage}`, cite(a.licenseFile)]);
  }
  out += '\nCONTENT BLOCKER\n\n' +
    `The blocker engine is built from unmodified npm releases of the Ghostery adblocker\n` +
    `(${bundle.engineVersion}) over the pinned filter lists. Its bundle's SHA-256 is\n${bundle.bundleSha256}.\n\n`;
  for (const p of bundle.packages)
    out += item(p.name, p.version, p.license, [`Source: ${p.source}`, ...p.licenseFiles.map(f => cite(`${BLOCKER}/${f.file}`))]);
  const r = bundle.proceduralRenderer;
  out += item(r.name, r.version, r.license, ['Source: https://github.com/ghostery/adblocker', ...r.licenseFiles.map(f => cite(`${BLOCKER}/${f.file}`))]);
  const resources = asset(bundle.ghosteryResources.id);
  out += item(resources.name, bundle.ghosteryResources.packageVersion, resources.license,
    [`Source: ${resources.homepage}/tree/${bundle.ghosteryResources.commit}`, `SHA-256: ${bundle.ghosteryResources.sha256}`, 'Licence text: as for @ghostery/adblocker above']);
  for (const list of bundle.filters.lists) {
    const a = asset(list.id);
    out += item(a.name, bundle.filters.date, a.license, [`Attribution: ${a.attribution}`, `Source: ${a.homepage}`, `Licence: ${a.licenseUrl}`, `SHA-256: ${list.sha256}`]);
  }
  out += '\nThe blocker\'s compiled rules are derived from EasyList and EasyPrivacy and keep their\n' +
    'CC BY-SA terms; the engine code keeps MPL-2.0.\n';
  out += '\nMPL SOURCE AVAILABILITY\n\n' +
    'The MPL-2.0 components above are unmodified releases (the procedural renderer adapts\n' +
    'the extended-selectors module); their source is at the links above, and Blanc\'s source,\n' +
    'including the bundling script, is at https://github.com/bnfy/blanc.\n';
  out += '\nLICENCE TEXTS\n';
  for (const {n, bytes} of texts.values()) out += `\n==== Licence text ${n} ====\n\n${bytes.toString('utf8').replace(/[ \t]+$/gm, '').replace(/\s+$/, '')}\n`;
  return out;
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const target = path.join(ROOT, NOTICE), expected = makeNotice();
  if (process.argv[2] === '--check') {
    if (fs.readFileSync(target, 'utf8') !== expected) { console.error(`${NOTICE} is out of date: run node chromium/release/fork-notice.mjs`); process.exitCode = 1; }
  } else { fs.writeFileSync(target, expected); console.log(`wrote ${NOTICE} (${expected.length} bytes)`); }
}
