// Model exactly the publicly readable paths. The publisher's signed-tree.json
// is private. Package hashes come from the owner's authenticated approval.
function stagingFixture({dep11 = false} = {}) {
  const objects = new Map(), rows = [];
  const put = key => objects.set(key, Buffer.from(key));
  const apt = 'deb/dists/stable/';
  for (const name of ['InRelease', 'Release.gpg']) put(apt + name);
  const listed = [];
  if (dep11) for (const deb of ['amd64', 'arm64']) {
    // As in a real tree, both architectures' catalogs are the same bytes and share by-hash files.
    for (const [suffix, bytes] of [['.yml', Buffer.from('catalog')], ['.yml.gz', Buffer.from('catalog gz')]]) {
      const name = 'main/dep11/Components-' + deb + suffix;
      objects.set(apt + name, bytes);
      objects.set(apt + 'main/dep11/by-hash/SHA256/' + sha256(bytes), bytes);
      listed.push(' ' + sha256(bytes) + ' ' + bytes.length + ' ' + name);
    }
  }
  objects.set(apt + 'Release', Buffer.from('Origin: Blanc\nSHA256:\n' + listed.join('\n') + '\n'));
  put('blanc-repository.asc');
  for (const [arch, deb, rpm] of [['x64', 'amd64', 'x86_64'], ['arm64', 'arm64', 'aarch64']]) {
    const index = apt + 'main/binary-' + deb + '/';
    for (const name of ['Packages', 'Packages.gz']) {
      put(index + name);
      const bytes = objects.get(index + name);
      objects.set(index + 'by-hash/SHA256/' + sha256(bytes), bytes);
    }
    const root = 'rpm/stable/' + rpm + '/';
    const entries = ['primary', 'filelists', 'other'].map(kind => {
      const bytes = Buffer.from(kind), href = 'repodata/' + sha256(bytes) + '-' + kind + '.xml.gz';
      objects.set(root + href, bytes);
      return '<data type="' + kind + '"><location href="' + href + '"/></data>';
    });
    objects.set(root + 'repodata/repomd.xml', Buffer.from('<repomd>' + entries.join('') + '</repomd>'));
    put(root + 'repodata/repomd.xml.asc');
    for (const version of [from, to]) for (const file of Object.values(packageNames(version, arch, 'beta'))) {
      const key = (file.endsWith('.rpm') ? root : 'deb/pool/main/b/blanc-beta/') + file;
      if (version === to) put(key);
      rows.push({file, size: key.length, sha256: sha256(key)});
    }
  }
  const digest = sha256([...objects.keys()].sort().map(key => sha256(objects.get(key)) + '  ' + key + '\n').join(''));
  const pointer = {generation: 908, digest, previous: []};
  const read = async key => {
    if (key === 'current.json') return Buffer.from(JSON.stringify(pointer));
    assert.ok(key.startsWith('generations/908/'), key);
    const bytes = objects.get(key.slice('generations/908/'.length));
    assert.ok(bytes, key);
    return bytes;
  };
  return {approval: {schema: 1, releaseVersion: to, packages: rows}, pointer, read, objects};
}

test('captures the DEP-11 catalog exactly when the signed Release lists it', async t => {
  const scratch = fs.mkdtempSync(path.join(os.tmpdir(), 'proof-dep11-'));
  t.after(() => fs.rmSync(scratch, {recursive: true, force: true}));
  const fixture = stagingFixture({dep11: true});
  const dir = fs.mkdtempSync(path.join(scratch, 'tree-'));
  await stageMetadata(inputs(), fixture.approval, dir, fixture.read);
  for (const deb of ['amd64', 'arm64']) {
    assert.equal(fs.readFileSync(path.join(dir, 'deb/dists/stable/main/dep11/Components-' + deb + '.yml'), 'utf8'), 'catalog');
    assert.equal(fs.readFileSync(path.join(dir, 'deb/dists/stable/main/dep11/Components-' + deb + '.yml.gz'), 'utf8'), 'catalog gz');
  }
  const missing = stagingFixture({dep11: true});
  missing.objects.delete('deb/dists/stable/main/dep11/Components-arm64.yml.gz');
  await assert.rejects(stageMetadata(inputs(), missing.approval, fs.mkdtempSync(path.join(scratch, 'tree-')), missing.read));
});

