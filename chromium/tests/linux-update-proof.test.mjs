test('the proof installers and lifecycle tree are bound to the detached approvals, version and exact bytes', async t => {
  // Keep the disposable agent socket below macOS's Unix socket path limit.
  const root = fs.mkdtempSync(path.join(process.platform === 'darwin' ? '/private/tmp' : os.tmpdir(), 'proof-key-'));
  const home = path.join(root, 'gpg');
  fs.mkdirSync(home, {mode: 0o700});
  t.after(() => {
    try { execFileSync('gpgconf', ['--homedir', home, '--kill', 'all']); }
    finally { fs.rmSync(root, {recursive: true, force: true}); }
  });
  const gpg = (...args) => execFileSync('gpg', ['--no-options', '--batch', '--homedir', home, ...args], {stdio: 'pipe'});
  gpg('--pinentry-mode', 'loopback', '--passphrase', '', '--quick-gen-key', 'Disposable proof approval', 'rsa2048', 'sign', '1d');
  const pub = path.join(root, 'fixture.asc');
  gpg('--armor', '--output', pub, '--export');
  const input = path.join(root, 'input');
  fs.mkdirSync(input);
  const spec = inputs('fedora'), bytes = Buffer.from('signed rpm');
  const {approval, objects, pointer, read} = stagingFixture();
  Object.assign(approval.packages.find(row => row.file === spec.oldPackage), {size: bytes.length, sha256: sha256(bytes)});
  const manifest = path.join(input, 'approved-packages.json');
  fs.writeFileSync(manifest, JSON.stringify(approval));
  fs.writeFileSync(path.join(input, spec.oldPackage), bytes);
  gpg('--armor', '--detach-sign', manifest);
  const check = (publicKey = pub, selected = spec) => verifyApproval(selected, input, fs.mkdtempSync(path.join(root, 'verify-')), publicKey);
  assert.deepEqual(check(), approval);
  // The native lifecycle needs the private signed inventory alongside the
  // staging metadata and both approved installers in its disposable system.
  const inventory = {schema: 1, digest: pointer.digest, files: [...objects.keys()].sort().map(p => ({path: p, sha256: sha256(objects.get(p))}))};
  const record = path.join(input, 'signed-tree.json');
  fs.writeFileSync(record, JSON.stringify(inventory));
  gpg('--armor', '--detach-sign', record);
  const poolFile = inventory.files.find(row => row.path.endsWith('/' + spec.newPackage)).path;
  fs.writeFileSync(path.join(input, spec.newPackage), objects.get(poolFile));
  const stage = async () => {
    const tree = fs.mkdtempSync(path.join(root, 'staged-'));
    await prepareLifecycleTree(spec, input, tree, read, pub);
    assert.deepEqual(fs.readFileSync(path.join(tree, poolFile)), objects.get(poolFile));
    assert.deepEqual(JSON.parse(fs.readFileSync(path.join(tree, 'signed-tree.json'))), inventory);
    assert.deepEqual(fs.readFileSync(path.join(tree, 'signed-tree.json.asc')), fs.readFileSync(record + '.asc'));
  };
  await stage();
  fs.appendFileSync(record, ' ');
  await assert.rejects(stage, /gpgv/);
  fs.truncateSync(record, fs.statSync(record).size - 1);
  fs.appendFileSync(path.join(input, spec.newPackage), 'wrong bytes');
  await assert.rejects(stage, /size|digest/);
  assert.throws(() => check(pub, proofInputs('fedora', 'x64', to, '158.0.8127.909', 'staging')));
  assert.throws(() => check(fileURLToPath(new URL('../linux/keys/blanc-repository.asc', import.meta.url))), /gpgv/);
  fs.writeFileSync(path.join(input, spec.oldPackage), Buffer.alloc(bytes.length));
  assert.throws(check, /digest/);
  fs.appendFileSync(path.join(input, spec.oldPackage), 'x');
  assert.throws(check, /size/);
  fs.appendFileSync(manifest, ' ');
  assert.throws(check, /gpgv/);
});

