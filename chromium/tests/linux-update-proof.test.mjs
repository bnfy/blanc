test('Task 5 dispatch selects all six native legs with only from, to and repository', () => {
  const workflow = YAML.parse(fs.readFileSync(new URL('../../.github/workflows/chromium-linux-candidate.yml', import.meta.url), 'utf8'));
  const dispatch = workflow.on.workflow_dispatch.inputs;
  assert.ok(dispatch.check.options.includes('update-proof'));
  for (const key of ['from', 'to', 'repository']) assert.ok(dispatch[key]);
  const job = workflow.jobs['update-proof'];
  assert.match(job.if, /inputs.check == 'update-proof'/);
  assert.deepEqual(job.strategy.matrix.arch, ['x64', 'arm64']);
  assert.deepEqual(job.strategy.matrix.system, ['ubuntu', 'debian', 'fedora']);
  assert.match(job['runs-on'], /matrix.arch.*ubuntu-24.04-arm.*ubuntu-24.04/);
  for (const arch of job.strategy.matrix.arch) for (const system of job.strategy.matrix.system) {
    const spec = inputs(system, arch);
    assert.equal(spec.archive, 'blanc-linux-beta-' + arch + '-907-candidate.tar.gz');
    assert.equal(spec.oldPackage, packageNames(from, arch, 'beta')[system === 'fedora' ? 'rpm' : 'deb']);
    assert.equal(spec.report, 'update-proof-' + system + '-' + arch + '.json');
  }
});

